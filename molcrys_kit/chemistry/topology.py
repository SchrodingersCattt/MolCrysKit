"""Exact periodic-rank analysis for quotient chemical graphs.

A bond crossing a unit-cell face does not by itself make a molecule periodic:
it may merely unwrap one finite molecule. Periodicity is instead generated by
non-zero lattice translations accumulated around graph cycles. This module
computes those cycle translations and their exact rank in three dimensions.
"""

from __future__ import annotations

import operator
from dataclasses import dataclass
from typing import Sequence

from .models import ChemicalBond, ImageShift


@dataclass(frozen=True)
class PeriodicTopology:
    """Translation subgroup generated by a connected quotient graph."""

    rank: int
    translation_generators: tuple[ImageShift, ...]

    def __post_init__(self) -> None:
        if self.rank not in {0, 1, 2, 3}:
            raise ValueError("periodic rank must be between zero and three")
        if len(self.translation_generators) != self.rank:
            raise ValueError("generator count must equal periodic rank")


def analyze_periodic_topology(
    atom_ids: tuple[str, ...],
    bonds: tuple[ChemicalBond, ...],
    *,
    periodic_axes: tuple[bool, bool, bool] = (True, True, True),
) -> PeriodicTopology:
    """Return the exact 0D--3D translation rank of a quotient graph.

    Tree-edge translations only choose contiguous images of graph vertices.
    Every non-tree edge contributes a closed-walk translation; the independent
    subset of those integer vectors defines the component dimension.
    """
    known = set(atom_ids)
    if any(bond.atom1_id not in known or bond.atom2_id not in known for bond in bonds):
        raise ValueError("bond endpoint is absent from atom_ids")
    if len(periodic_axes) != 3:
        raise ValueError("periodic_axes must contain three booleans")

    mask = tuple(int(value) for value in periodic_axes)
    adjacency: dict[str, list[tuple[str, ImageShift]]] = {
        atom_id: [] for atom_id in atom_ids
    }
    for bond in bonds:
        shift = tuple(
            int(value) * periodic
            for value, periodic in zip(bond.atom2_image_shift, mask)
        )
        reverse = tuple(-value for value in shift)
        adjacency[bond.atom1_id].append((bond.atom2_id, shift))
        adjacency[bond.atom2_id].append((bond.atom1_id, reverse))

    potentials: dict[str, ImageShift] = {}
    cycle_translations: set[ImageShift] = set()
    for root in atom_ids:
        if root in potentials:
            continue
        potentials[root] = (0, 0, 0)
        stack = [root]
        while stack:
            atom_id = stack.pop()
            for neighbor_id, shift in adjacency[atom_id]:
                proposed = tuple(
                    left + right for left, right in zip(potentials[atom_id], shift)
                )
                if neighbor_id not in potentials:
                    potentials[neighbor_id] = proposed
                    stack.append(neighbor_id)
                    continue
                residual = tuple(
                    left - right
                    for left, right in zip(proposed, potentials[neighbor_id])
                )
                canonical = _canonical_translation(residual)
                if canonical != (0, 0, 0):
                    cycle_translations.add(canonical)

    independent: list[ImageShift] = []
    for candidate in sorted(cycle_translations, key=_generator_sort_key):
        if _integer_rank((*independent, candidate)) > len(independent):
            independent.append(candidate)
        if len(independent) == 3:
            break
    return PeriodicTopology(len(independent), tuple(independent))


def integer_translation_basis(
    vectors: Sequence[Sequence[int]],
) -> tuple[ImageShift, ...]:
    """Return the column-style Hermite basis of an integer translation lattice.

    ``vectors`` are the columns of a 3×n integer matrix. Unimodular column
    operations reduce that matrix to lower-triangular Hermite form: positive
    pivots, zeros strictly above each pivot, and entries below a pivot reduced
    into ``[0, pivot)``. The nonzero columns are the basis of every integer
    combination of the input. A single ``(2, 0, 0)`` therefore stays
    ``(2, 0, 0)``; ``(2, 0, 0)`` together with ``(3, 0, 0)`` becomes
    ``(1, 0, 0)``.

    This is the lattice basis used by coordination-polyhedron networks. It is
    intentionally separate from :func:`analyze_periodic_topology`, whose
    generators are an independent subset of the input cycle translations and
    are not replaced by their Hermite reduction.
    """
    columns: list[list[int]] = []
    for vector in vectors:
        if len(vector) != 3:
            raise ValueError("a translation vector must have three components")
        column = [_exact_int(component) for component in vector]
        if any(column):
            columns.append(column)
    return tuple(tuple(column) for column in _column_hermite_form(columns))


def _exact_int(value: object) -> int:
    if isinstance(value, bool):
        raise TypeError("translation components must be exact integers, got bool")
    try:
        return int(operator.index(value))
    except TypeError as exc:
        raise TypeError(
            f"translation components must be exact integers, got {type(value).__name__}"
        ) from exc


def _extended_gcd(left: int, right: int) -> tuple[int, int, int]:
    """Return ``(g, s, t)`` with ``g = s * left + t * right`` and ``g > 0``."""
    old_r, current_r = left, right
    old_s, current_s = 1, 0
    old_t, current_t = 0, 1
    while current_r != 0:
        quotient = old_r // current_r
        old_r, current_r = current_r, old_r - quotient * current_r
        old_s, current_s = current_s, old_s - quotient * current_s
        old_t, current_t = current_t, old_t - quotient * current_t
    if old_r < 0:
        return -old_r, -old_s, -old_t
    return old_r, old_s, old_t


def _column_hermite_form(columns: list[list[int]]) -> list[list[int]]:
    """Lower-triangular column Hermite form; zero columns are dropped."""
    if not columns:
        return []
    matrix = [list(column) for column in columns]
    width = len(matrix)
    pivot_column = 0
    for row in range(3):
        if pivot_column >= width:
            break
        source = next(
            (
                column
                for column in range(pivot_column, width)
                if matrix[column][row] != 0
            ),
            None,
        )
        if source is None:
            continue
        if source != pivot_column:
            matrix[pivot_column], matrix[source] = matrix[source], matrix[pivot_column]
        for other in range(pivot_column + 1, width):
            if matrix[other][row] == 0:
                continue
            pivot_value = matrix[pivot_column][row]
            other_value = matrix[other][row]
            gcd, pivot_coeff, other_coeff = _extended_gcd(pivot_value, other_value)
            combined = [
                pivot_coeff * matrix[pivot_column][index]
                + other_coeff * matrix[other][index]
                for index in range(3)
            ]
            complement_pivot = -(other_value // gcd)
            complement_other = pivot_value // gcd
            complement = [
                complement_pivot * matrix[pivot_column][index]
                + complement_other * matrix[other][index]
                for index in range(3)
            ]
            matrix[pivot_column] = combined
            matrix[other] = complement
        if matrix[pivot_column][row] < 0:
            matrix[pivot_column] = [-value for value in matrix[pivot_column]]
        pivot_value = matrix[pivot_column][row]
        for earlier in range(pivot_column):
            quotient = matrix[earlier][row] // pivot_value
            if quotient:
                matrix[earlier] = [
                    value - quotient * pivot
                    for value, pivot in zip(matrix[earlier], matrix[pivot_column])
                ]
        pivot_column += 1
    return [column for column in matrix[:pivot_column] if any(column)]


def _canonical_translation(vector) -> ImageShift:
    values = tuple(int(value) for value in vector)
    first_nonzero = next((value for value in values if value), 0)
    if first_nonzero < 0:
        return tuple(-value for value in values)
    return values


def _generator_sort_key(vector: ImageShift) -> tuple[int, int, int, int, int]:
    first_axis = next(index for index, value in enumerate(vector) if value)
    return (sum(value * value for value in vector), first_axis, *vector)


def _integer_rank(vectors: tuple[ImageShift, ...]) -> int:
    nonzero = [vector for vector in vectors if any(vector)]
    if not nonzero:
        return 0
    first = nonzero[0]
    second = next(
        (vector for vector in nonzero[1:] if any(_cross(first, vector))),
        None,
    )
    if second is None:
        return 1
    for third in nonzero[1:]:
        cross = _cross(second, third)
        determinant = sum(left * right for left, right in zip(first, cross))
        if determinant != 0:
            return 3
    return 2


def _cross(left: ImageShift, right: ImageShift) -> ImageShift:
    return (
        left[1] * right[2] - left[2] * right[1],
        left[2] * right[0] - left[0] * right[2],
        left[0] * right[1] - left[1] * right[0],
    )


